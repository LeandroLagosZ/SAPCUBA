-- Script completo de la base apertura_cuentas (tablas, índices, datos, procedimientos, triggers, vistas, reportes y roles)
-- Equivale a ejecutar en orden db/01 ... db/08. Requiere PostgreSQL 11 o superior (CREATE PROCEDURE / CALL)
-- y un usuario con permiso CREATEROLE (por ejemplo postgres), porque el último bloque crea los roles de acceso.

-- ===== 01_tablas.sql =====
CREATE SEQUENCE seq_contrato START 20000;

CREATE TABLE departamento (
  cod_departamento SMALLINT PRIMARY KEY,
  nombre_departamento VARCHAR(40) NOT NULL UNIQUE);
CREATE TABLE provincia (
  cod_provincia SMALLINT PRIMARY KEY,
  nombre_provincia VARCHAR(40) NOT NULL,
  cod_departamento SMALLINT NOT NULL REFERENCES departamento ON DELETE RESTRICT);
CREATE TABLE ocupacion (
  cod_ocupacion SMALLINT PRIMARY KEY,
  nombre_ocupacion VARCHAR(20) NOT NULL UNIQUE);
CREATE TABLE moneda (
  cod_moneda SMALLINT PRIMARY KEY,
  nombre_moneda VARCHAR(20) NOT NULL UNIQUE,
  cod_internacional CHAR(3) NOT NULL UNIQUE,
  simbolo VARCHAR(5) NOT NULL,
  estado SMALLINT NOT NULL DEFAULT 1 CHECK (estado IN (0,1)));
CREATE TABLE agencia (
  cod_agencia SMALLINT PRIMARY KEY,
  nombre_agencia VARCHAR(60) NOT NULL,
  calle VARCHAR(100) NOT NULL,
  cod_provincia SMALLINT NOT NULL REFERENCES provincia ON DELETE RESTRICT,
  anexo VARCHAR(10) NOT NULL UNIQUE,
  estado SMALLINT NOT NULL DEFAULT 1 CHECK (estado IN (0,1)));
CREATE TABLE cliente (
  cod_cliente INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1003) PRIMARY KEY,
  dni CHAR(8) NOT NULL UNIQUE CHECK (dni ~ '^[0-9]{8}$'),
  nombres VARCHAR(50) NOT NULL CHECK (length(btrim(nombres)) > 0),                    -- atributos atómicos (1FN), como en la Cuarta Entrega
  apellido_paterno VARCHAR(50) NOT NULL CHECK (length(btrim(apellido_paterno)) > 0),
  apellido_materno VARCHAR(50) NOT NULL CHECK (length(btrim(apellido_materno)) > 0),
  fecha_nacimiento DATE NOT NULL CHECK (fecha_nacimiento <= CURRENT_DATE),
  correo VARCHAR(80) NOT NULL UNIQUE,
  estado SMALLINT NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  cod_ocupacion SMALLINT NOT NULL REFERENCES ocupacion ON DELETE RESTRICT,
  cod_provincia SMALLINT NOT NULL REFERENCES provincia ON DELETE RESTRICT,  -- provincia de residencia del cliente (no la de la agencia)
  calle VARCHAR(100) NOT NULL CHECK (length(btrim(calle)) > 0),               -- dirección del cliente
  fecha_emision_dni DATE NOT NULL,
  peruano_residente BOOLEAN NOT NULL CHECK (peruano_residente),               -- confirmó nacionalidad peruana con domicilio y residencia en Perú
  CHECK (fecha_emision_dni <= CURRENT_DATE AND fecha_emision_dni >= fecha_nacimiento));
CREATE TABLE telefono_clientes (
  cod_cliente INT NOT NULL REFERENCES cliente ON DELETE CASCADE,
  numero_telefono VARCHAR(9) NOT NULL CHECK (numero_telefono ~ '^[0-9]{9}$'),
  PRIMARY KEY (cod_cliente, numero_telefono));
CREATE TABLE cuenta_ahorros (
  numero_cuenta VARCHAR(20) PRIMARY KEY CHECK (numero_cuenta ~ '^[0-9]{20}$'),
  cod_interbancario VARCHAR(20) NOT NULL UNIQUE CHECK (cod_interbancario ~ '^[0-9]{20}$'),
  n_contrato INT NOT NULL UNIQUE DEFAULT nextval('seq_contrato'),
  tasa_interes NUMERIC(5,2) NOT NULL DEFAULT 0.00 CHECK (tasa_interes BETWEEN 0 AND 100),
  saldo NUMERIC(14,2) NOT NULL DEFAULT 0.00 CHECK (saldo >= 0),
  estado SMALLINT NOT NULL DEFAULT 1 CHECK (estado IN (0,1)),
  cod_cliente INT NOT NULL REFERENCES cliente ON DELETE RESTRICT,
  cod_moneda SMALLINT NOT NULL REFERENCES moneda ON DELETE RESTRICT,
  cod_agencia SMALLINT NOT NULL REFERENCES agencia ON DELETE RESTRICT);
CREATE TABLE tarjeta (
  numero_tarjeta VARCHAR(16) PRIMARY KEY CHECK (numero_tarjeta ~ '^[0-9]{16}$'),
  codigo_tarjeta CHAR(3) NOT NULL CHECK (codigo_tarjeta ~ '^[0-9]{3}$'),  -- texto: conserva los ceros iniciales (007)
  estado SMALLINT NOT NULL CHECK (estado IN (0,1)),
  fecha_emision DATE NOT NULL,
  fecha_vencimiento DATE NOT NULL,
  marca VARCHAR(20) NOT NULL,
  numero_cuenta VARCHAR(20) NOT NULL REFERENCES cuenta_ahorros ON DELETE RESTRICT,
  CHECK (fecha_vencimiento > fecha_emision));

-- ===== 02_indices.sql =====
CREATE INDEX idx_provincia_departamento ON provincia (cod_departamento);
CREATE INDEX idx_agencia_provincia ON agencia (cod_provincia);
CREATE INDEX idx_cliente_ocupacion ON cliente (cod_ocupacion);
CREATE INDEX idx_cliente_provincia ON cliente (cod_provincia);
